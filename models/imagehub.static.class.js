class IntervalHub {

    static everyInterval = [];

    static setStoppableInterval(fn, time){
        let newInterval = setInterval(fn, time);
        IntervalHub.everyInterval.push(newInterval);
        return newInterval;
    }

    static stopEveryInterval(){
        IntervalHub.everyInterval.forEach(clearInterval);
        IntervalHub.everyInterval = [];
    }

    static stopInterval(fn){
        clearInterval(fn);
    }
}

class AudioHub {
    // Audiodateien
    static backgroundMusic = new Audio('./audio/backgroundmusic.mp3');
    static win = new Audio('./audio/win-screen.mp3');
    static loose = new Audio('./audio/loose-screen.mp3');
    static click = new Audio('./audio/mouseclick.mp3');
    static charHurt = new Audio('./audio/char-hurt.mp3');
    static charDying = new Audio('./audio/char-dying.mp3');
    static chickenHurt = new Audio('./audio/chicken-hurt.mp3');
    static throwBottle = new Audio('./audio/throw-bottle.mp3');

    // Array, dass alle Sounds enthält
    static allSounds = [
        AudioHub.backgroundMusic,
        AudioHub.win,
        AudioHub.loose,
        AudioHub.click,
        AudioHub.charHurt,
        AudioHub.charDying,
        AudioHub.chickenHurt,
        AudioHub.throwBottle,
    ];

    // abspielen von einem Sound
    static playSound(sound){
        sound.volume = 0.2;
        sound.currentTime = 0;
        sound.play();
    }
    
    // Abspielen stoppen
    static stopAll(){
        AudioHub.allSounds.forEach(sound => {
            sound.pause();
        });
        document.getElementById('volume').value = 0.2;
    }

    // Abspielen von einem Sound stoppen
    static stopOneSound(){
        sound.pause();
    }

    // Lautstärke regeln
    static setVolume(volumeSlider){
        let volumeValue = document.getElementById('volume').value;
        volumeSlider.forEach(sound => {
            sound.volume = volumeValue;
        })
    }
}